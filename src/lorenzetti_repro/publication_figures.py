def _bin_edges(axis,source=None):
    # Stable original Lorenzetti binning (Notebook 211, 221); plot fallback.
    return ETA_EDGES if axis=='eta' else ENERGY_EDGES

def _bins(d,axis):
    position=(d.abs_eta.to_numpy() if axis=='eta' else d.E_true_MeV.to_numpy())
    edges=_bin_edges(axis);return position,edges

def _series_by_bin(frame,axis,stat):
    d=_arr(frame);pos,edges=_bins(d,axis)
    pred=d.alpha_calib.to_numpy();base=d.E_true_MeV.to_numpy()/d.E_fast_MeV.to_numpy()
    xs=[];y=[];bars=[];f=[]
    for j,(a,b) in enumerate(zip(edges[:-1],edges[1:])):
        mask=(pos>=a)&((pos<b) if j<len(edges)-2 else (pos<=b))
        if sum(mask)<15: continue
        x=pred[mask]; z=base[mask];err=z-x
        xs.append((a+b)/2/(1000 if axis=='energy' else 1));bars.append(len(x))
        if stat=='iqr':y.append(np.percentile(x,75)-np.percentile(x,25));f.append(np.percentile(z,75)-np.percentile(z,25))
        elif stat=='rmse':y.append(np.sqrt(np.mean(err*err)))
        elif stat=='mae':y.append(np.mean(abs(err)))
    return np.asarray(xs),np.asarray(y),np.asarray(f),np.asarray(bars)

def _draw_alpha(frames,out,kind='iqr'):
    plt=_plt();fig,axes=plt.subplots(1,2,figsize=(11,4.5))
    for i,axis in enumerate(['eta','energy']):
        ax=axes[i]
        for name,frame in frames.items():
            d=_arr(frame)
            if axis=='eta' and 'abs_eta' not in d:continue
            if kind=='iqr':
                x,y,base,_=_series_by_bin(frame,axis,'iqr')
                ax.plot(x,y,marker='.',lw=1.2,label=name)
            else:
                x,y,_,_=_series_by_bin(frame,axis,'rmse')
                _,mae,_,_=_series_by_bin(frame,axis,'mae')
                ax.plot(x,y,marker='.',lw=1.0,label=name+' RMSE')
                ax.plot(x,mae,ls='--',lw=.9,label=name+' MAE')
        ax.set(xlabel='|η|' if axis=='eta' else '$E_{true}$ (GeV)',
               ylabel='IQR($\\alpha_{calib}$)' if kind=='iqr' else 'Error of $\\alpha_{calib}$',
               title='By pseudorapidity' if axis=='eta' else 'By true energy')
        ax.legend(fontsize=6)
    _save(fig,out)

def _draw_alpha_box(frames,out):
    plt=_plt();fig,axes=plt.subplots(1,2,figsize=(12,5))
    for a,axis in zip(axes,['eta','energy']):
        matrix=[];labels=[]
        for name,frame in list(frames.items())[:2]:
            d=_arr(frame)
            if axis=='eta' and 'abs_eta' not in d:continue
            pos,edges=_bins(d,axis)
            for j,(lo,hi) in enumerate(zip(edges[:-1],edges[1:])):
                mask=(pos>=lo)&(pos<(hi if j<len(edges)-2 else hi+1e-6))
                if mask.sum()<30:continue
                matrix.append(d.alpha_calib.to_numpy()[mask])
                labels.append(f'{name.split(":")[-1].strip()}: {lo/(1000 if axis=="energy" else 1):g}–{hi/(1000 if axis=="energy" else 1):g}')
        if matrix:
            a.boxplot(matrix,vert=False,showfliers=False)
            a.set_yticks(np.arange(1,len(labels)+1));a.set_yticklabels(labels,fontsize=5.3)
            a.set(xlabel='$\\alpha_{calib}$',title='|η| bins' if axis=='eta' else 'Energy bins')
        else:a.text(.5,.5,'No saved pseudorapidity values',transform=a.transAxes)
    _save(fig,out)

def _draw_resolution(frames,out):
    aligned,msg=check_alignment(frames)
    if not aligned:raise ValueError('Resolution curves need aligned per-event vectors: '+msg)
    plt=_plt();fig,ax=plt.subplots(figsize=(9,5))
    first=_arr(next(iter(frames.values())))
    samples=[('Standard FastCalo',first.E_fast_MeV.to_numpy())]
    samples.extend((label,_arr(frame).E_calib_MeV.to_numpy()) for label,frame in frames.items())
    truth=first.E_true_MeV.to_numpy();edges=np.linspace(truth.min(),truth.max(),21)
    for name,vals in samples:
        xx=[];yy=[];ee=[]
        for i,(a,b) in enumerate(zip(edges[:-1],edges[1:])):
            mask=(truth>=a)&((truth<b) if i<19 else (truth<=b))
            n=int(mask.sum())
            if n<100:continue
            ratio=vals[mask]/truth[mask]
            xx.append((a+b)/2000)
            st=float(np.std(ratio,ddof=1));yy.append(st)
            ee.append(st/np.sqrt(2*(n-1)))
        ax.errorbar(xx,yy,yerr=ee,fmt='.-',capsize=1.5,label=name,lw=1.1)
    ax.set(xlabel='$E_{true}$ (GeV)',ylabel='$\\sigma_E/E$',title='Relative energy resolution by true-energy bin')
    ax.legend(fontsize=7);_save(fig,out)

