def figure_scoped_frames(article,kind,active):
    if kind not in ('ear','qq','scatter'):
        return active
    terms={
     ('tns','qq'):('BDT no-Bin: PCA-10',),
     ('measurement','ear'):('RFBDT no-Bin: Rings[1:100]','BDT no-Bin: ICA-5'),
     ('measurement','qq'):('RFBDT no-Bin: Rings[1:100]','BDT no-Bin: Rings[1:100]'),
     ('measurement','scatter'):('RFBDT no-Bin: Rings[1:100]','BDT no-Bin: ICA-5'),
     ('information_fusion','ear'):('GNN no-Bin: Rings[1:100]','DNN no-Bin: ICA-10'),
     ('information_fusion','qq'):('GNN no-Bin: Rings[1:100]','DNN no-Bin: CORR-10'),
     ('information_fusion','scatter'):('GNN no-Bin: Rings[1:100]','DNN no-Bin: ICA-10'),
    }
    wanted=terms.get((article,kind),())
    if not wanted:return active
    found={canonical(x):x for x in active}
    return {found[canonical(x)]:active[found[canonical(x)]] for x in wanted if canonical(x) in found}

def generate(article:str,frames:dict,bundles:dict,output:str|Path,*,data_csv=None,
             timing_csv=None, only_numbers=None):
    """Calculate publication figures and tables from research artifacts.

    Plots are not produced when their required research data are missing.
    See figure_manifest.json for completeness.
    """
    if article not in FIGURES:raise ValueError(article)
    directory=Path(output);directory.mkdir(parents=True,exist_ok=True)
    chosen,missing=selected_frames(frames,article)
    active=frames  # All archived experiment configurations, not only publication highlights.
    tables=compute_event_tables(active) if active else {}
    if tables:save_tables(tables,directory/'tables')
    metrics=tables.get('metrics',pd.DataFrame())
    timing=timing_from_archived_bundles(bundles)
    if timing_csv is not None:
        tab=pd.read_csv(timing_csv)
        if not {'configuration','time_ms_per_event'}.issubset(tab.columns):
            raise ValueError('Timing CSV requires configuration,time_ms_per_event')
        timing=tab[['configuration','time_ms_per_event']]
    if not timing.empty:timing.to_csv(directory/'tables'/'timing.csv',index=False)
    all_figures=FIGURES[article]
    if only_numbers is not None:
        unknown=set(only_numbers)-set(all_figures)
        if unknown:raise ValueError(f'Figures outside selected publication: {sorted(unknown)}')
        all_figures={i:k for i,k in all_figures.items() if i in set(only_numbers)}
    registry=[]
    for number,kind in all_figures.items():
        output_file=directory/f'Fig_{number:02d}_{kind}.png'
        entry={'figure':number,'type':kind,'file':output_file.name,'source':'computed from archive and/or original Lorenzetti CSV',
               'input_configurations':list(active)}
        try:
            if kind=='feature_relevance':
                if data_csv is None:raise FileNotFoundError('Original dataset CSV needed for D70 CORR/MI/PCA/ICA relevance')
                from .feature_relevance import draw_feature_relevance
                draw_feature_relevance(data_csv,output_file)
            elif not active and kind=='benchmark_energy' and data_csv is not None:
                _draw_benchmark_csv(data_csv,output_file)
            elif not active:
                raise FileNotFoundError('Missing archived per-event predictions for this article')
            elif kind=='stage1_tradeoff':_draw_stage1_tradeoff(output_file,metrics,timing)
            elif kind=='gain_summary':_fig_gain(output_file,chosen,metrics)
            elif kind=='latency':_fig_latency(output_file,metrics,timing)
            elif kind=='benchmark_energy':_draw_benchmark(active,output_file)
            elif kind=='error_distribution':_draw_distribution(frames,output_file)
            elif kind=='alpha_iqr':_draw_alpha(chosen or active,output_file,'iqr')
            elif kind=='alpha_error':_draw_alpha(chosen or active,output_file,'rmse')
            elif kind=='alpha_box':_draw_alpha_box(chosen or active,output_file)
            elif kind=='resolution':_draw_resolution(chosen or active,output_file)
            elif kind=='ear':
                fig_frames=figure_scoped_frames(article,kind,chosen)
                if not fig_frames:raise FileNotFoundError('Required article models missing for EAR')
                _draw_ear(fig_frames,output_file)
            elif kind=='scatter':
                fig_frames=figure_scoped_frames(article,kind,chosen)
                if not fig_frames:raise FileNotFoundError('Required article models missing for scatter')
                _draw_scatter(fig_frames,output_file)
            elif kind=='qq':
                fig_frames=figure_scoped_frames(article,kind,chosen)
                if not fig_frames:raise FileNotFoundError('Required article models missing for Q–Q')
                _draw_qq(fig_frames,output_file)
            elif kind=='ranking':_fig_rank(active,output_file,metrics,timing)
            else:raise ValueError('Unmapped chart type: '+kind)
            if not output_file.is_file() or output_file.stat().st_size<500:
                raise RuntimeError('Plot output missing/empty')
            entry['status']='generated'
        except (FileNotFoundError,ValueError,KeyError,ImportError,AttributeError,RuntimeError) as exc:
            output_file.unlink(missing_ok=True)
            entry['status']='missing_input';entry['reason']=str(exc)
        registry.append(entry)
    pd.DataFrame(registry).to_csv(directory/'figure_manifest.csv',index=False)
    (directory/'figure_manifest.json').write_text(json.dumps(registry,indent=2,ensure_ascii=False),encoding='utf8')
    return registry,missing
