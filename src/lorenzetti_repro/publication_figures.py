def canonical(label):
    """Normalized comparison key, preserving PCA-10 != PCA-100."""
    s=str(label).upper().replace(' ','').replace('NOSEG','NO-BIN').replace('NOBIN','NO-BIN')
    s=s.replace('RINGS1:100','RINGS[1:100]').replace('(B)','').replace('RINGS[1-100]','RINGS[1:100]')
    return s

def selected_frames(all_frames:dict,article:str):
    """Return named published configurations, never substitute another silently."""
    indexed={canonical(x):x for x in all_frames}
    selected={}; missing=[]
    for wanted in PRIORITIES[article]:
        key=canonical(wanted)
        if key in indexed: selected[indexed[key]]=all_frames[indexed[key]]
        else:missing.append(wanted)
    return selected,missing

def check_alignment(frames):
    """Check event ordering before cross-model comparisons; never pair mismatched rows."""
    names=list(frames)
    if not names:return False,'no event arrays'
    one=event_values(frames[names[0]])
    for name in names[1:]:
        other=event_values(frames[name])
        if len(one)!=len(other):return False,f'different event counts: {name}'
        for col in ('E_true_MeV','E_fast_MeV'):
            if not np.allclose(one[col],other[col],rtol=1e-12,atol=1e-6):
                return False,f'event ordering / reference mismatch: {name} / {col}'
    return True,'aligned event vectors'

