def _fig_gain(out,frames,metrics):
    """Fig. 37: relative improvements recalculated from saved event predictions."""
    if metrics.empty:raise FileNotFoundError('Missing event-level arrays for performance gains')
    if not frames:raise FileNotFoundError('No selected publication configurations were found in the archived event predictions')
    rows=[]
    for name,frame in frames.items():
        d=_arr(frame);et=d.E_true_MeV.to_numpy()
        rc=resolution_by_energy(et,d.E_calib_MeV.to_numpy())
        rf=resolution_by_energy(et,d.E_fast_MeV.to_numpy())
        resolution_gain=100*(1-rc.relative_resolution.mean()/rf.relative_resolution.mean())
        grid,cc,bb=shared_ear(et,d.E_calib_MeV.to_numpy(),d.E_fast_MeV.to_numpy(),points=1000)
        lc=delta_lambda_90(grid,cc);lb=delta_lambda_90(grid,bb)
        g=metrics.loc[metrics.configuration==name].iloc[0]
        rows.append({'configuration':name,'RMSE':g.rmse_reduction_pct,'IQR':g.iqr_reduction_pct,
                     'Relative resolution':resolution_gain,
                     'EAR 90%':100*(1-lc/lb) if lb and lc is not None else np.nan})
    values=pd.DataFrame(rows).set_index('configuration')
    plt=_plt();fig,ax=plt.subplots(figsize=(11,6))
    values.T.plot.bar(ax=ax,rot=0,width=.8)
    ax.set(ylabel='Relative improvement (%)',title='Improvements computed from archived predictions')
    ax.legend(fontsize=7);_save(fig,out)

