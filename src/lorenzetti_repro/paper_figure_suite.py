def _stage1_tradeoff(frames,timing_csv,output,bundles=None):
    """Original notebook cells 736, 739 and 741 with measured archived inputs."""
    from .original_article_cells import SOURCE_CELLS
    from .analysis_tables import configuration_feature_count, compute_D0
    from .original_plotting import full_data_text_label
    import matplotlib.pyplot as plt
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    from .analysis_tables import archived_feature_counts
    feature_lookup=archived_feature_counts(bundles or {})
    rows=[]
    for label,frame in frames.items():
        d=event_values(frame);e=d.residual_calib_MeV.to_numpy(float)
        rmse=float(np.sqrt(np.mean(e**2)));iqr=float(np.diff(np.quantile(e,[.25,.75]))[0])
        rows.append({'Method-Selection':label,'RMSE (MeV)':rmse,'IQR (MeV)':iqr,
                     'd0 (GeV)':float(np.hypot(rmse,iqr))/1000.0,
                     'Number of Features':feature_lookup.get(label,configuration_feature_count(label))})
    df=pd.DataFrame(rows).sort_values('d0 (GeV)').head(10).copy()
    outputs={};errors={}
    def run(tag,code,data):
        try:
            with collect_shows(output,tag) as paths:
                c={'np':np,'pd':pd,'plt':plt,'full_data_text_label':source_figure_label(),
                   'metrics_result_DF_d0_time_features':data}
                exec(SOURCE_CELLS[str(code)],c,c)
            if not paths:raise RuntimeError('No figure was generated')
            outputs[tag]=list(paths)
        except Exception as e:errors[tag]=f'{type(e).__name__}: {e}'
    if len(df)>=10:
        run('paper_stage1_iqr_rmse',736,df)
        if df['Number of Features'].notna().all():
            run('paper_stage1_d0_features',741,df)
        else:errors['paper_stage1_d0_features']='Exact retained feature counts are missing from the archived performance metrics.'
    else:
        errors['paper_stage1_iqr_rmse']=f'Original figure requires ten configurations; {len(df)} are stored.'
        errors['paper_stage1_d0_features']=errors['paper_stage1_iqr_rmse']
    if timing_csv and Path(timing_csv).is_file():
        try:
            times=pd.read_csv(timing_csv)
            if not {'configuration','time_ms_per_event'}.issubset(times):
                raise KeyError('configuration,time_ms_per_event columns')
            df=df.merge(times[['configuration','time_ms_per_event']],
                     left_on='Method-Selection',right_on='configuration',how='inner',validate='one_to_one')
            if len(df)<10:raise ValueError('Original chart requires measured times for ten top-ranked configurations')
            df['Time (ms)']=df.time_ms_per_event
            run('paper_stage1_d0_time',739,df)
        except Exception as e:errors['paper_stage1_d0_time']=f'{type(e).__name__}: {e}'
    else:errors['paper_stage1_d0_time']='The historical numeric prediction times are missing.'
    return outputs,errors

STAGE2_MODELS=[('RFBDT','Rings[1:100]'),('BDT','ICA-5'),('BDT','PCA-10'),('BDT','Rings[1:100]')]

def _stage2_extras(frames, timing_csv, output):
    from .original_inline_figures import plot_original_fig37, plot_original_fig38
    from .original_plotting import global_resolution_with_uncertainty
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    canonical={label:event_values(frame) for label,frame in frames.items()}
    found=[];missing=[]
    for method,representation in STAGE2_MODELS:
        matched=[label for label in canonical if exact_configuration(label,method,representation)]
        if len(matched)!=1:missing.append(f'{method}: {representation} (found {len(matched)})')
        else:found.append(matched[0])
    if missing:return {},{'paper_stage2_performance':'Missing exact archived configurations: '+', '.join(missing)}
    first=canonical[found[0]]
    for label in found[1:]:
        d=canonical[label]
        if len(d)!=len(first) or not np.array_equal(d.E_true_MeV,first.E_true_MeV) or not np.array_equal(d.E_fast_MeV,first.E_fast_MeV):
            return {},{'paper_stage2_performance':'The four archived models are not paired by identical events.'}
    fast=first.residual_fast_MeV.to_numpy(float)
    et=first.E_true_MeV.to_numpy(float)
    ef=first.E_fast_MeV.to_numpy(float)
    rmsef=np.sqrt(np.mean(fast**2))
    iqrf=np.subtract(*np.quantile(fast,[.75,.25]))
    # difference sign does not change absolute IQR or RMSE
    iqrf=abs(float(iqrf))
    resolution_fast=global_resolution_with_uncertainty(ef,et)[0]
    def ear_width(e,grid):
        j=np.searchsorted(np.sort(np.abs(e)),grid,side='left')/len(e)
        k=np.flatnonzero(j>=.90)
        return float(grid[k[0]]) if len(k) else np.nan
    matrix=[];d0s=[float(np.hypot(rmsef,iqrf))]
    for label in found:
        d=canonical[label];e=d.residual_calib_MeV.to_numpy(float)
        rmse=np.sqrt(np.mean(e**2));iqr=float(np.diff(np.quantile(e,[.25,.75]))[0]);
        resolution=global_resolution_with_uncertainty(d.E_calib_MeV.to_numpy(float),et)[0]
        grid=np.linspace(0,6*max(np.std(fast),np.std(e)),1000)
        w_fast=ear_width(fast,grid);w_calib=ear_width(e,grid)
        matrix.append([100*(1-rmse/rmsef),100*(1-iqr/iqrf),
                       100*(1-resolution/resolution_fast),100*(1-w_calib/w_fast)])
        d0s.append(float(np.hypot(rmse,iqr)))
    outputs={};failures={}
    try:
        with collect_shows(output,'paper_stage2_performance') as figs:
            plot_original_fig37(matrix,['Standard FastCalo']+found)
        outputs['paper_stage2_performance']=list(figs)
    except Exception as e:failures['paper_stage2_performance']=f'{type(e).__name__}: {e}'
    csv=Path(timing_csv) if timing_csv else None
    if csv and csv.is_file():
        try:
            t=pd.read_csv(csv)
            if not {'configuration','time_ms_per_event'}.issubset(t.columns):
                raise ValueError('Missing configuration and time_ms_per_event columns')
            times=[]
            for label in found:
                subset=t.loc[t.configuration==label,'time_ms_per_event']
                if len(subset)!=1 or not np.isfinite(subset.iloc[0]) or subset.iloc[0]<=0:
                    raise ValueError(f'Historical numeric prediction time missing for {label}')
                times.append(float(subset.iloc[0]))
            with collect_shows(output,'paper_stage2_tradeoff') as figs:
                plot_original_fig38(['Standard FastCalo']+found,[0]+times,d0s,[0,100,5,10,100])
            outputs['paper_stage2_tradeoff']=list(figs)
        except Exception as e: failures['paper_stage2_tradeoff']=f'{type(e).__name__}: {e}'
    else: failures['paper_stage2_tradeoff']='Original prediction times not available; export numeric timing metadata.'
    return outputs,failures


def reproduce_paper_figure_set(article,frames,bundles,output,*,data_csv=None,timing_csv=None,
                                new_run=False,include_raw=True):
    """Compute and index every paper result figure from the experiment's data.

    The number of generated *files* can exceed the paper figure count, because
    some paper figures contain multiple panels originally displayed separately.
    """
    if article not in PAPER_OUTPUTS:raise ValueError(f'Unknown article: {article}')
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    raw={'paths':{},'failures':{}}
    if include_raw and data_csv is not None:
        raw=generate_source_diagnostics(data_csv,output/'source_diagnostics')
    elif include_raw:
        raw['failures']={k:'Original Lorenzetti CSV required' for k in (
            'original_true_fast_histogram','original_true_fast_scatter','original_standardized_error_histogram',
            'original_error_distribution_fit','original_true_alpha_eta','original_true_alpha_energy',
            'original_100_ring_boxplot','original_feature_relevance')}
    replay=replay_original_figures(article,frames,bundles,output/'trained_model_figures',data_csv=data_csv,
                   allow_nonpublication_reference=new_run)
    # Original notebook result section, beyond the paper-only comparison set.
    full=generate_full_original_analyses(article,frames,bundles,
            output/'additional_result_figures',timing_csv=timing_csv)
    source_paths=[p for paths in raw['paths'].values() for p in paths]
    supplementary_paths=[p for paths in full['paths'].values() for p in paths]
    generated=source_paths+replay.get('figure_paths',[])+supplementary_paths
    failures=dict(raw['failures'])
    failures.update(full.get('errors',{}))
    for note in replay.get('notes',[]):
        if isinstance(note,dict):failures[note.get('analysis','unknown')]=note.get('reason','missing input')
    if article=='tns':
        extra,extra_fail=_stage1_tradeoff(frames,timing_csv,output/'trained_model_figures',bundles)
        generated.extend(p for group in extra.values() for p in group)
        failures.update(extra_fail)
    if article=='measurement':
        extra,extra_fail=_stage2_extras(frames,timing_csv,output/'trained_model_figures')
        generated.extend(p for group in extra.values() for p in group)
        failures.update(extra_fail)
    rows=[]
    for num,(title,required) in PAPER_OUTPUTS[article].items():
        matches=[];missing=[]
        for prefix in required:
            if prefix in ('original_segmented_iqr','original_segmented_error'):
                # The two ETA/ET curves are produced in source function
                # integrated_plots_in_ETA_ET_geral_with_ranges. Identify the
                # EXACT plt.show() source lines, rather than guessing from
                # rendered text (which differs between matplotlib backends).
                original_source_lines = ({552,976} if prefix.endswith('iqr')
                                         else {698,1136})
                def matches_panel(p):
                    if not (p.name.startswith('original_segmented_') and p.suffix.lower()=='.png'):
                        return False
                    meta=p.with_suffix('.json')
                    if not meta.exists():return False
                    m=json.loads(meta.read_text(encoding='utf8'))
                    if m.get('source_function')=='integrated_plots_in_ETA_ET_geral_with_ranges':
                        return m.get('source_line') in original_source_lines
                    # Backward-compatible strict title/axis match.
                    keyword='IQR Integrated' if prefix.endswith('iqr') else 'Estimation Error Integrated'
                    return any(keyword in (a.get('title','')+' '+a.get('ylabel',''))
                               for a in m.get('axes',[]))
                hits=[p for p in generated if matches_panel(p)]
                # Both energy and pseudorapidity panels are required.
                if len(hits)<2:missing.append(prefix)
                matches.extend(hits)
                continue
            else:
                hits=[p for p in generated if p.name.startswith(prefix)]
            if hits:matches.extend(hits)
            else:missing.append(prefix)
        status='generated' if not missing else ('partial' if matches else 'missing_input')
        rows.append({'paper':article,'figure':num,'description':title,'status':status,
                     'files':' | '.join(str(p.relative_to(output)) for p in dict.fromkeys(matches)),
                     'missing_source_groups':' | '.join(missing),
                     'error':' | '.join(str(failures.get(p,'unknown dependency')) for p in missing)})
    coverage=pd.DataFrame(rows)
    coverage.to_csv(output/'paper_figure_coverage.csv',index=False)
    (output/'paper_figure_coverage.json').write_text(coverage.to_json(orient='records',indent=2),encoding='utf8')
    return {'coverage':coverage,'files':list(dict.fromkeys(generated)),
            'original_report':replay,'source_report':raw,'supplementary_report':full,'errors':failures}
